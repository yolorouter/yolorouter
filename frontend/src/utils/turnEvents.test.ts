// frontend/src/utils/turnEvents.test.ts
//
// Table-driven unit matrices for the replay's read-side event
// classification (pure functions — node env, no DOM). The classification
// MIRRORS the backend's write-time rules one-to-one
// (internal/agentturns/classify.go — the persisted turn store's event
// taxonomy), so the classification table below deliberately pins the SAME
// arm set the backend's own table pins (derive_test.go's
// TestClassifyAddedMessage): the marker table, the tool_result structural
// checks, the empty-text arm, and the total/catch-all arms, one backend
// arm for every frontend arm and vice versa. If either table grows, both
// do — a classification change on one side fails the other side's table.
import { describe, expect, it } from 'vitest'
import {
  buildAddedSegments,
  classifyAddedMessage,
  collectToolNames,
  extractToolResults,
  firstPreviewLine,
  toolResultDetail,
} from './turnEvents'
import { translateMessageArray, translateStreamBody, type TranslatedBody } from './messageTranslator'

// ---------------------------------------------------------------------------
// Classification mirror (classify.go's table)
// ---------------------------------------------------------------------------

describe('classifyAddedMessage (the backend rule table, mirrored)', () => {
  it.each<[string, unknown, 'user_input' | 'tool_result' | 'injected']>([
    ['plain human text', { role: 'user', content: '1+1' }, 'user_input'],
    ['human text in content blocks', { role: 'user', content: [{ type: 'text', text: '看看这个仓库' }] }, 'user_input'],
    ['empty text', { role: 'user', content: '' }, 'user_input'],
    ['system-reminder wrapper', { role: 'user', content: '<system-reminder>\nResult of a call' }, 'injected'],
    ['system-reminder inside blocks', { role: 'user', content: [{ type: 'text', text: '<system-reminder>\n…' }] }, 'injected'],
    ['command-name echo', { role: 'user', content: '<command-name>/compact</command-name>' }, 'injected'],
    ['command-message echo', { role: 'user', content: '<command-message>compact</command-message>' }, 'injected'],
    ['local-mode caveat', { role: 'user', content: 'Caveat: The messages below were generated by the user while running local commands.' }, 'injected'],
    ['ide_selection block', { role: 'user', content: [{ type: 'text', text: '<ide_selection>lines 1 to 1 of a.jsonl</ide_selection>' }] }, 'injected'],
    ['ide_opened_file string content', { role: 'user', content: '<ide_opened_file>The user opened the file b.jsonl in the IDE.' }, 'injected'],
    ['marker must LEAD the text (mid-text is quoted content)', { role: 'user', content: '关于 Caveat: 的讨论' }, 'user_input'],
    ['leading whitespace before the marker still counts', { role: 'user', content: '\n  <system-reminder>hi' }, 'injected'],
    ['anthropic tool_result block alone', { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }] }, 'tool_result'],
    ['Anthropic tool_result block wins over the text beside it', { role: 'user', content: [{ type: 'text', text: 'ok' }, { type: 'tool_result', tool_use_id: 't1', content: 'out' }] }, 'tool_result'],
    ['OpenAI role:tool message', { role: 'tool', tool_call_id: 'c1', content: 'exit 0' }, 'tool_result'],
    ['no role: the catch-all keeps it on the axis', { content: 'payload' }, 'user_input'],
    ['unrecognized role: the catch-all keeps it on the axis', { role: 'developer', content: 'house rules' }, 'user_input'],
    ['non-object element: stays on the axis, never dropped', 'stray string', 'user_input'],
    ['null content', { role: 'user', content: null }, 'user_input'],
  ])('classifies %s', (_name, input, expected) => {
    expect(classifyAddedMessage(input)).toBe(expected)
  })
})

