// Segment building (the graded walk)
// ---------------------------------------------------------------------------

describe('buildAddedSegments', () => {
  it('grades a mixed added slice in wire order: tool results as cards, injected runs folded, humans as bubbles', () => {
    const segments = buildAddedSegments([
      { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't1', content: 'total 0\nexit 0' }] },
      { role: 'user', content: '<system-reminder>\nInjected A' },
      { role: 'user', content: '<command-name>/compact</command-name>' },
      { role: 'user', content: '人类输入' },
    ])
    expect(segments.map((s) => s.kind)).toEqual(['tool_result', 'injected', 'user'])
    // The tool_result segment carries the wire id + raw content for the
    // card (name resolution happens in the page's cross-turn index).
    expect(segments[0]).toEqual({ kind: 'tool_result', toolUseId: 't1', content: 'total 0\nexit 0' })
    // The two consecutive injected messages fold into ONE run of two.
    expect(segments[1]).toEqual({ kind: 'injected', count: 2, texts: ['<system-reminder>\nInjected A', '<command-name>/compact</command-name>'] })
    // The human input translates to a renderable chat message.
    expect(segments[2].kind).toBe('user')
    if (segments[2].kind === 'user') {
      expect(segments[2].message.role).toBe('user')
      expect(segments[2].message.text).toBe('人类输入')
    }
  })

  it('separates injected runs split by a human input (two runs, each with its own count)', () => {
    const segments = buildAddedSegments([
      { role: 'user', content: '<system-reminder>\nfirst run' },
      { role: 'user', content: 'a question' },
      { role: 'user', content: 'Caveat: second run' },
    ])
    expect(segments.map((s) => s.kind)).toEqual(['injected', 'user', 'injected'])
    expect(segments[0]).toMatchObject({ count: 1 })
    expect(segments[2]).toMatchObject({ count: 1 })
  })

  it('grades the block-split wire form: per-block injected elements fold into one run, the human element bubbles', () => {
    // What the backend ships since the block-level split: a user message
    // that mixed IDE context with human words arrives as SEPARATE wire
    // elements (injected per machine block, one per kept run) — the mirror
    // must collapse the machine elements behind one counted line and keep
    // the words on the axis, never leaking ide text into the bubble.
    const segments = buildAddedSegments([
      { role: 'user', content: [{ type: 'text', text: '<ide_selection>lines 1-1 of a.jsonl</ide_selection>' }] },
      { role: 'user', content: [{ type: 'text', text: '<ide_opened_file>opened b.jsonl</ide_opened_file>' }] },
      { role: 'user', content: [{ type: 'text', text: '补充这个字段' }] },
    ])
    expect(segments.map((s) => s.kind)).toEqual(['injected', 'user'])
    expect(segments[0]).toEqual({
      kind: 'injected',
      count: 2,
      texts: ['<ide_selection>lines 1-1 of a.jsonl</ide_selection>', '<ide_opened_file>opened b.jsonl</ide_opened_file>'],
    })
    if (segments[1].kind !== 'user') throw new Error('expected a user segment')
    expect(segments[1].message.text).toBe('补充这个字段')
    expect(segments[1].message.text).not.toContain('<ide_')
  })

  it('emits sibling tool_result segments for a parallel-call message', () => {
    const segments = buildAddedSegments([
      {
        role: 'user',
        content: [
          { type: 'tool_result', tool_use_id: 't1', content: 'a' },
          { type: 'tool_result', tool_use_id: 't2', content: 'b' },
        ],
      },
    ])
    expect(segments.map((s) => s.kind)).toEqual(['tool_result', 'tool_result'])
    expect(segments.map((s) => (s.kind === 'tool_result' ? s.toolUseId : ''))).toEqual(['t1', 't2'])
  })

  it('drops nothing renderable and adds nothing empty: noise slices yield no filler', () => {
    expect(buildAddedSegments([])).toEqual([])
    // An empty user message (content '') renders no empty bubble.
    expect(buildAddedSegments([{ role: 'user', content: '' }])).toEqual([])
    // A non-record stray stays classified user_input but has nothing to show.
    expect(buildAddedSegments(['stray'])).toEqual([])
    // A message whose text exists renders exactly one user segment.
    expect(buildAddedSegments([{ role: 'user', content: 'hi' }])).toHaveLength(1)
  })

  it('keeps a structurally-classified tool_result with no extractable payload visible as a card', () => {
    // role:tool always extracts; the fallback arm covers a user message
    // classified tool_result whose blocks carry no tool_result payload —
    // an impossible shape today, guarded for content safety tomorrow.
    const segments = buildAddedSegments([{ role: 'user', content: [{ type: 'tool_result' }] }])
    expect(segments).toHaveLength(1)
    expect(segments[0].kind).toBe('tool_result')
  })
})

