describe('extractToolResults', () => {
  it('lifts one payload per tool_result block (parallel calls arrive as siblings)', () => {
    const m = {
      role: 'user',
      content: [
        { type: 'tool_result', tool_use_id: 't1', content: [{ type: 'text', text: 'first' }] },
        { type: 'tool_result', tool_use_id: 't2', content: 'second' },
      ],
    }
    expect(extractToolResults(m)).toEqual([
      { toolUseId: 't1', content: [{ type: 'text', text: 'first' }] },
      { toolUseId: 't2', content: 'second' },
    ])
  })

  it('lifts the OpenAI role:tool message as one payload keyed by tool_call_id', () => {
    expect(extractToolResults({ role: 'tool', tool_call_id: 'c1', content: 'exit 0' })).toEqual([
      { toolUseId: 'c1', content: 'exit 0' },
    ])
  })

  it('yields nothing for non-tool-result shapes', () => {
    expect(extractToolResults({ role: 'user', content: 'hi' })).toEqual([])
    expect(extractToolResults('stray')).toEqual([])
  })
})

