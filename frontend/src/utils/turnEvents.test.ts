describe('collectToolNames', () => {
  it('indexes tool ids → names across translated bodies (all sources feed it)', () => {
    const streamBody: TranslatedBody = translateStreamBody(
      [
        'data: {"type":"content_block_start","index":0,"content_block":{"type":"tool_use","id":"toolu_s","name":"Bash","input":{}}}',
        'data: {"type":"content_block_delta","index":0,"delta":{"type":"input_json_delta","partial_json":"{}"}}',
        'data: {"type":"message_stop"}',
      ].join('\n'),
    )
    const resendBody = translateMessageArray([
      { role: 'assistant', content: [{ type: 'tool_use', id: 'toolu_r', name: 'Read', input: {} }] },
    ])
    const map = new Map<string, string>()
    collectToolNames(streamBody, map)
    collectToolNames(resendBody, map)
    expect(map.get('toolu_s')).toBe('Bash')
    expect(map.get('toolu_r')).toBe('Read')
  })

  it('indexes OpenAI tool_call ids too, and skips parts without ids or names', () => {
    const body = translateMessageArray([
      { role: 'assistant', content: null, tool_calls: [{ id: 'c1', type: 'function', function: { name: 'get_weather', arguments: '{}' } }] },
    ])
    const map = new Map<string, string>()
    collectToolNames(body, map)
    expect(map.get('c1')).toBe('get_weather')
    // A placeholder body contributes nothing and does not throw.
    collectToolNames({ kind: 'placeholder', messages: [], truncated: false }, map)
    expect(map.size).toBe(1)
  })
})

describe('preview helpers', () => {
  it('toolResultDetail reduces blocks content to text like the whole-body path', () => {
    expect(toolResultDetail('raw string')).toBe('raw string')
    expect(toolResultDetail([{ type: 'text', text: 'line 1' }, { type: 'text', text: 'line 2' }])).toBe('line 1\nline 2')
    expect(toolResultDetail(null)).toBe('')
  })

  it('firstPreviewLine takes the first non-empty line, capped with an ellipsis', () => {
    expect(firstPreviewLine('\n\n  total 0\nexit 0')).toBe('total 0')
    expect(firstPreviewLine('x'.repeat(150))).toBe('x'.repeat(100) + '…')
    expect(firstPreviewLine('   \n  ')).toBe('')
  })
})
